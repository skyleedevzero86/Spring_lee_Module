export function readLocale(): LocaleId {
  const saved = localStorage.getItem('tts-locale')
  if (saved === 'ko' || saved === 'ja' || saved === 'zh' || saved === 'en') {
    return saved
  }
  return 'ko'
}

export const i18n = createI18n({
  legacy: false,
  locale: readLocale(),
  fallbackLocale: 'en',
  messages,
})
